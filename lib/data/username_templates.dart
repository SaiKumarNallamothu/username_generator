  static List<String> generateAISuggestions(String keyword, String category) {
    List<String> prefixes = aiPrefixes[category] ?? aiPrefixes['Cool']!;
    List<String> suffixes = aiSuffixes[category] ?? aiSuffixes['Cool']!;
    
    List<String> suggestions = [];
    
    // Mix keyword with prefix
    for (var prefix in prefixes.take(4)) {
      suggestions.add('$prefix$keyword');
    }
    // Mix keyword with suffix
    for (var suffix in suffixes.take(4)) {
      suggestions.add('$keyword$suffix');
    }
    // Custom formats
    if (prefixes.isNotEmpty && suffixes.isNotEmpty) {
      suggestions.add('${prefixes[0]}$keyword${suffixes[0]}');
      suggestions.add('$keyword${prefixes[1]}');
    }
    
    // Ensure all unique
    return suggestions.toSet().toList();
  }
